"""Rebuild RESULTS.md from all result files results/<label>/*.json (run after adding or merging results).

  python results_table.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MAX_HASHES = 3


def cell(stats: dict | None) -> str:
    if not stats:
        return "–"
    items = list(stats["hashes"].items())
    shown = ", ".join(f"`{h}`×{c}" for h, c in items[:MAX_HASHES])
    more = f" (+{len(items) - MAX_HASHES} more)" if len(items) > MAX_HASHES else ""
    return (f"{shown}{more} – {'repeatable' if stats['repeatable'] else '**not repeatable**'}, "
            f"{'= ref' if stats['equals_reference'] else '**≠ ref**'}")


def row(r: dict) -> str:
    m = r["machine"]
    gpus = ", ".join(g["name"] for g in m.get("gpus", [])) or "CPU"
    return (f"| {r['label']} | {r['started'][:16].replace('T', ' ')} | {m.get('os', '')} | {gpus} | "
            f"{m.get('ollama')} / {m.get('server', {}).get('build_info')} | {cell(r['temperatures'].get('0'))} | "
            f"{cell(r['temperatures'].get('1'))} | {len(r.get('warnings', []))} | {r.get('note', '')} |")


def build(root: Path = ROOT) -> str:
    reference = json.loads((root / "reference.json").read_text(encoding="utf-8"))
    records = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(root.glob("results/*/*.json"))]
    records.sort(key=lambda r: (r["label"], r["started"]))
    lines = ["# Results", "",
             "Generated by `results_table.py` from `results/*/*.json` – do not edit by hand.", "",
             f"Reference: temperature 0 = `{reference['hashes']['0']}`, temperature 1 = `{reference['hashes']['1']}`.",
             "",
             "| machine | started | OS | GPU | Ollama / llama.cpp build | temperature 0 | temperature 1 | warnings | note |",
             "|---|---|---|---|---|---|---|---|---|"]
    return "\n".join(lines + [row(r) for r in records]) + "\n"


def main() -> None:
    md = build()
    (ROOT / "RESULTS.md").write_text(md, encoding="utf-8", newline="\n")
    print(f"RESULTS.md: {md.count(chr(10)) - 8} results")


if __name__ == "__main__":
    main()
